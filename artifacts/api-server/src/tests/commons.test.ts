test("fee quotes use 4%+4%, immutable deterministic ids and cumulative refund reconciliation", () => {
  const q = quoteFees(10000);
  assert.equal(q.buyerTotalMinor, 10400);
  assert.equal(q.sellerNetMinor, 9600);
  assert.equal(q.platformGrossMinor, 800);
  assert.equal(Object.isFrozen(q), true);
  assert.equal(q.id, quoteFees(10000).id);
  for (const n of [1, 12, 13, 99, 101, 9999, 10000]) {
    const full = quoteFees(n, n);
    assert.equal(full.refundBuyerMinor, full.buyerTotalMinor);
    assert.equal(full.refundSellerMinor, full.sellerNetMinor);
    assert.equal(full.refundPlatformMinor, full.platformGrossMinor);
    let buyer = 0, seller = 0, platform = 0, previous = quoteFees(n, 0);
    for (let r = 1; r <= n; r++) {
      const now = quoteFees(n, r);
      buyer += now.refundBuyerMinor - previous.refundBuyerMinor;
      seller += now.refundSellerMinor - previous.refundSellerMinor;
      platform += now.refundPlatformMinor - previous.refundPlatformMinor;
      previous = now;
    }
    assert.equal(buyer - seller, platform);
    assert.equal(buyer, full.buyerTotalMinor);
  }
  assert.throws(() => quoteFees(1.1));
  assert.throws(() => quoteFees(100, 101));
  assert.throws(() => quoteFees(Number.MAX_SAFE_INTEGER));
});

test("disposable DB schema: real Git, tenant isolation, drafts, invitations, proposals and merge replay", async () => {
  // The schema name is generated by this test, never from a request.
  const schema = `gitai_test_${randomUUID().replaceAll("-", "")}`;
  const client = await pool.connect();
  const repositories: string[] = [];
  const setupConnection = (connection: { query: (s: string) => unknown }) => { connection.query(`SET search_path TO "${schema}"`); };
  try {
    await client.query(`CREATE SCHEMA "${schema}"`);
    await client.query(`CREATE TABLE "${schema}".gitai_records (LIKE public.gitai_records INCLUDING ALL)`);
    await client.query(`SET search_path TO "${schema}"`);
    pool.on("connect", setupConnection);
    client.release();
    const alice = commons.subject("synthetic-alice"), bob = commons.subject("synthetic-bob");
    await assert.rejects(commons.createRecord("", { kind: "profile", title: "No identity", body: "", data: {} }), /Sign in/);
    const profile = await commons.createRecord(alice, { kind: "profile", title: "Synthetic operator", body: "Disposable fixture", data: { kind: "human", operatorLabel: "Synthetic Alice", verification: "self-reported" } });
    assert.equal(profile.data.operator, alice);
    assert.equal((await commons.listRecords("")).length, 0);
    await assert.rejects(commons.changeRecord(bob, profile.id, { action: "edit", title: "Hijack" }), /not found/);
    await assert.rejects(commons.changeRecord(alice, profile.id, { action: "approve" }), /configured community owner/);
    const repo = await commons.createRecord(alice, { kind: "repository", title: "Synthetic repo", body: "", data: { slug: "synthetic", visibility: "private", license: "UNLICENSED" } });
    repositories.push(repo.id);
    const initial = await commons.repositoryDetail(alice, repo.id);
    assert.equal(initial.commits.length, 1);
    assert.equal(initial.files[0].path, "README.md");
    await assert.rejects(commons.repositoryDetail(bob, repo.id), /not found/);
    await assert.rejects(commons.proposeChange(bob, repo.id, { base: initial.head, path: "attack.md", content: "bad", message: "bad" }), /not found/);
    for (const path of ["../escape", ".git/config", "x/../../etc", "/absolute", "a//b", "a/hooks/x"]) assert.throws(() => safePath(path));
    const p = await commons.proposeChange(alice, repo.id, { base: initial.head, path: "notes.md", content: "Actual Git blob\n", message: "Add notes" });
    assert.equal((await commons.repositoryDetail(alice, repo.id)).proposals.length, 1);
    await assert.rejects(commons.mergeChange(alice, repo.id, { proposalId: p.id, reviewed: false }), /review/);
    await commons.mergeChange(alice, repo.id, { proposalId: p.id, reviewed: true });
    const after = await commons.repositoryDetail(alice, repo.id);
    assert.equal(after.commits.length, 2);
    assert.equal(after.files.find(f => f.path === "notes.md")?.content, "Actual Git blob\n");
    await assert.rejects(commons.mergeChange(alice, repo.id, { proposalId: p.id, reviewed: true }), /not found/);
    await assert.rejects(commons.proposeChange(alice, repo.id, { base: initial.head, path: "old.md", content: "", message: "stale" }), /Base changed/);
    const service = await commons.createRecord(alice, { kind: "service", title: "Synthetic review", body: "Draft only", data: { category: "Review", subtotalMinor: 10000, deadlineDays: 3, offerType: "offer" } });
    assert.equal(service.status, "pending");
    const post = await commons.createRecord(alice, { kind: "post", title: "Synthetic topic", body: "<script>not executable</script>", data: { topic: "engineering", label: "opinion" } });
    const comment = await commons.createRecord(alice, { kind: "comment", title: "Reply", body: "A reply", data: { parentId: post.id } });
    assert.equal(comment.status, "pending");
    await assert.rejects(commons.createRecord(bob, { kind: "comment", title: "Intrude", body: "", data: { parentId: post.id } }), /not found/);
    await pool.query("UPDATE gitai_records SET status = 'approved' WHERE id = ANY($1::text[])", [[post.id, comment.id, service.id]]);
    assert.equal((await commons.listRecords("")).some(r => r.id === comment.id), true);
    await commons.changeRecord(alice, post.id, { action: "delete" });
    assert.equal((await commons.listRecords("")).some(r => r.id === comment.id), false);
    const invitation = await commons.createRecord(alice, { kind: "invitation", title: "Synthetic invitation", body: "Not sent", data: { recipient: "fixture", expiresAt: new Date(Date.now() + 3600000).toISOString(), role: "member", scope: "community-only" } });
    assert.equal(invitation.status, "draft");
    await assert.rejects(commons.changeRecord(alice, invitation.id, { action: "accept" }), /closed/);
    await pool.query("UPDATE gitai_records SET data = jsonb_set(data, '{expiresAt}', to_jsonb($1::text)) WHERE id = $2", ["2020-01-01T00:00:00.000Z", invitation.id]);
    assert.equal((await commons.listRecords(alice)).find(r => r.id === invitation.id)?.status, "expired");
    await commons.changeRecord(alice, invitation.id, { action: "revoke" });
    await assert.rejects(commons.createRecord(alice, { kind: "invitation", title: "Expired", body: "", data: { recipient: "fixture", expiresAt: "2020-01-01T00:00:00.000Z", role: "member", scope: "community-only" } }), /expiry/);
    await commons.changeRecord(alice, service.id, { action: "delete" });
    assert.equal((await commons.listRecords(alice)).some(r => r.id === service.id), false);
  } finally {
    pool.off("connect", setupConnection);
    for (const id of repositories) removeRepo(id);
    const cleanup = await pool.connect();
    await cleanup.query(`DROP SCHEMA "${schema}" CASCADE`);
    cleanup.release();
    await pool.end();
  }
});
